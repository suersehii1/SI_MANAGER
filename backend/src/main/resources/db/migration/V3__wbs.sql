-- ===== wbs_items =====
CREATE TABLE wbs_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT        NOT NULL,
    parent_id     BIGINT,
    sort_order    INTEGER       NOT NULL DEFAULT 0,
    name          VARCHAR(200)  NOT NULL,
    description   VARCHAR(4000),
    deliverable   VARCHAR(200),
    assignee_id   BIGINT,
    status        VARCHAR(20)   NOT NULL DEFAULT 'NOT_STARTED',
    weight        NUMERIC(5,2)  NOT NULL DEFAULT 1.00,
    planned_start DATE,
    planned_end   DATE,
    actual_start  DATE,
    actual_end    DATE,
    progress      INTEGER       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_wbs_name CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_wbs_status CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'DONE', 'ON_HOLD')),
    CONSTRAINT ck_wbs_weight CHECK (weight > 0 AND weight <= 999.99),
    CONSTRAINT ck_wbs_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_wbs_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_wbs_planned_period CHECK (
        planned_start IS NULL OR planned_end IS NULL OR planned_end >= planned_start),
    CONSTRAINT ck_wbs_actual_period CHECK (
        actual_end IS NULL OR (actual_start IS NOT NULL AND actual_end >= actual_start)),
    CONSTRAINT fk_wbs_project  FOREIGN KEY (project_id)  REFERENCES projects (id)  ON DELETE CASCADE,
    CONSTRAINT fk_wbs_parent   FOREIGN KEY (parent_id)   REFERENCES wbs_items (id) ON DELETE CASCADE,
    CONSTRAINT fk_wbs_assignee FOREIGN KEY (assignee_id) REFERENCES users (id)     ON DELETE SET NULL
);
CREATE INDEX ix_wbs_project_parent_order ON wbs_items (project_id, parent_id, sort_order);
CREATE INDEX ix_wbs_parent ON wbs_items (parent_id);
CREATE INDEX ix_wbs_assignee ON wbs_items (assignee_id);
